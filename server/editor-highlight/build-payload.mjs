import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const directory = new URL("./", import.meta.url);
const result = await build({
  entryPoints: [fileURLToPath(new URL("payload.ts", directory))],
  bundle: true,
  write: false,
  platform: "browser",
  format: "iife",
  globalName: "ToolkitEditorHighlight",
  minify: true,
  legalComments: "none",
});
const license = await readFile(new URL("../../LICENSE.editor-highlight", directory), "utf8");
const payload = `/*!\n${license}*/\n${result.outputFiles[0].text}`;
await writeFile(
  new URL("payload.generated.ts", directory),
  `// Generated by npm run build:editor-highlight. See LICENSE.editor-highlight.\nexport const payload = ${JSON.stringify(payload)};\n`,
);
